// Run after build-browser-fixture.mjs. Uses an existing Playwright installation:
// $env:DSH_TASK_PLAYWRIGHT = '<absolute path to playwright-core/index.mjs>'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import assert from 'node:assert/strict'
if (!process.env.DSH_TASK_PLAYWRIGHT) throw new Error('Set DSH_TASK_PLAYWRIGHT to the existing playwright-core/index.mjs')
const { chromium } = await import(pathToFileURL(process.env.DSH_TASK_PLAYWRIGHT).href)
const root = resolve(import.meta.dirname, '../.browser-test')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  page.on('pageerror', error => { errors.push(error.message); console.error('Browser error:', error.message) })
  // Mock fixture routes in this test browser only. No server is started or changed.
  await page.route('https://task-fixture.test/**', async route => {
    const name = route.request().url().endsWith('fixture.js') ? 'fixture.js' : 'index.html'
    await route.fulfill({ contentType: name.endsWith('.js') ? 'text/javascript' : 'text/html', body: await readFile(resolve(root, name)) })
  })
  await page.goto('https://task-fixture.test/index.html')
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  const editor = page.getByRole('textbox', { name: '内容（必填）' })
  const sessionPicker = page.getByRole('combobox', { name: '关联会话', exact: true })
  assert.equal(await sessionPicker.inputValue(), '')
  assert.deepEqual(await sessionPicker.locator('option').allTextContents(), ['不关联会话', '当前中文会话', '另一个中文会话'])
  await sessionPicker.selectOption({ label: '另一个中文会话' })
  await editor.fill('测试富文本')
  await editor.press('Control+a')
  await page.getByRole('button', { name: '加粗', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '加粗', exact: true }).getAttribute('aria-pressed'), 'true')
  await editor.press('Control+s')
  assert.equal(await page.evaluate(() => window.fixture.captures().length), 0, 'task editor must not trigger composer capture')
  await page.locator('input[type="file"]').setInputFiles({ name: 'requirements.txt', mimeType: 'text/plain', buffer: Buffer.from('abc') })
  await page.getByRole('button', { name: 'requirements.txt', exact: true }).waitFor()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  const row = await page.evaluate(() => window.fixture.tasks()[0])
  assert.equal(row.sessionId, 'session-other')
  assert.equal(row.content.blocks[0].children[0].text, '测试富文本')
  assert.deepEqual(row.content.blocks[0].children[0].marks, ['bold'])
  assert.equal(row.content.blocks.at(-1).name, 'requirements.txt')
  await page.getByRole('button', { name: /编辑: 测试富文本/ }).click()
  assert.equal(await sessionPicker.inputValue(), 'session-other')
  assert.equal(await sessionPicker.locator('option:checked').innerText(), '另一个中文会话')
  await page.evaluate(() => window.fixture.renameSession('session-other', '更新后的中文标题'))
  await sessionPicker.getByRole('option', { name: '更新后的中文标题', exact: true }).waitFor({ state: 'attached' })
  assert.equal(await sessionPicker.locator('option:checked').innerText(), '更新后的中文标题')
  await sessionPicker.selectOption('')
  assert.equal(await editor.locator('strong,b,[class*="bold"]').innerText(), '测试富文本')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'requirements.txt', exact: true }).click()
  const download = await downloadPromise
  assert.equal(download.suggestedFilename(), 'requirements.txt')
  assert.equal(String(await readFile(await download.path())), 'abc')
  await page.getByRole('button', { name: '加粗', exact: true }).hover()
  await page.getByRole('tooltip', { name: '加粗' }).waitFor()
  await page.mouse.move(100, 100)
  await page.getByRole('tooltip').waitFor({ state: 'hidden' })
  await page.screenshot({ path: resolve(root, 'light.png') })
  await page.evaluate(() => {
    const root = document.documentElement.style
    root.setProperty('--dsw-alias-label-primary', '#eee')
    root.setProperty('--dsw-alias-label-secondary', '#a2a8b3')
    root.setProperty('--dsw-alias-bg-base', '#181a20')
    root.setProperty('--dsw-alias-border-l3', '#45474d')
    root.setProperty('--dsw-alias-interactive-bg-hover', '#303238')
  })
  await page.screenshot({ path: resolve(root, 'dark.png') })
  await page.setViewportSize({ width: 420, height: 900 })
  const toolbarBox = await page.getByRole('toolbar', { name: '文字格式' }).boundingBox()
  assert.ok(toolbarBox.x >= 0 && toolbarBox.x + toolbarBox.width <= 420)
  await page.screenshot({ path: resolve(root, 'narrow.png') })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: '移除附件: requirements.txt' }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.fixture.tasks()[0].content.blocks.some(block => block.type === 'attachment')), false)
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  await editor.focus()
  await editor.evaluate(element => {
    const data = new DataTransfer()
    data.setData('text/html', '<h1>网页标题</h1><p><span style="font-weight:700;font-style:italic;text-decoration:underline">Word文字</span> <a href="https://example.com">安全链接</a><a href="javascript:alert(1)">危险链接</a></p><ul><li>第一项<ul><li>子项</li></ul></li></ul><table><tr><th>字段</th><th>值</th></tr><tr><td>名称</td><td><strong>测试</strong></td></tr></table><img src="https://example.com/remote.png"><script>window.pasteExecuted=true</script>')
    data.setData('text/plain', 'fallback')
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
  })
  await editor.locator('table').waitFor()
  assert.equal(await page.evaluate(() => window.pasteExecuted), undefined)
  assert.equal(await editor.locator('img,script,[onclick]').count(), 0)
  assert.equal(await editor.locator('a[href^="javascript:"]').count(), 0)
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  const pasted = await page.evaluate(() => window.fixture.tasks()[0])
  assert.equal(pasted.content.blocks[0].type, 'heading')
  assert.equal(pasted.content.blocks[0].level, 1)
  const marked = pasted.content.blocks.flatMap(block => block.children ?? []).find(child => child.text === 'Word文字')
  assert.deepEqual(new Set(marked.marks), new Set(['bold', 'italic', 'underline']))
  assert.ok(pasted.content.blocks.flatMap(block => block.children ?? []).some(child => child.href === 'https://example.com'))
  assert.ok(pasted.content.blocks.some(block => block.type === 'bullet' && block.indent === 1))
  assert.equal(pasted.content.blocks.find(block => block.type === 'table').rows[1][1].blocks[0].children[0].text, '测试')
  await page.getByRole('button', { name: /编辑: 网页标题/ }).click()
  assert.equal(await editor.locator('h1').innerText(), '网页标题')
  assert.equal(await editor.locator('td').last().innerText(), '测试')
  assert.equal(await editor.locator('ul ul').count(), 1)
  await editor.press('Control+End')
  await editor.press('End')
  await editor.press('Enter')
  await page.keyboard.insertText('撤销测试')
  await editor.press('Control+z')
  assert.ok(!(await editor.innerText()).includes('撤销测试'))
  await editor.press('Control+y')
  assert.ok((await editor.innerText()).includes('撤销测试'))
  await page.getByRole('button', { name: '取消', exact: true }).click()
  const composer = page.getByRole('textbox', { name: '测试对话输入框' })
  await composer.fill('一起保存文件和图片')
  await page.evaluate(() => window.fixture.stageFiles([
    new File(['document bytes'], '需求.docx', { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' }),
    new File([new Uint8Array([137, 80, 78, 71])], '截图.png', { type: 'image/png' }),
  ]))
  await composer.press('Control+s')
  await page.waitForFunction(() => window.fixture.captures().length === 1)
  await page.waitForFunction(() => window.fixture.input().attachmentIds.length === 0)
  const captured = await page.evaluate(() => window.fixture.captures()[0])
  assert.equal(captured.sessionId, 'session-current', 'Ctrl+S must keep the composer session')
  assert.equal(captured.content.blocks[0].children[0].text, '一起保存文件和图片')
  assert.deepEqual(captured.content.blocks.filter(block => block.type === 'attachment').map(block => block.name), ['需求.docx', '截图.png'])
  assert.equal(Buffer.from(captured.attachments[0].data, 'base64').toString(), 'document bytes')
  assert.deepEqual([...Buffer.from(captured.attachments[1].data, 'base64')], [137, 80, 78, 71])
  assert.equal(await page.evaluate(() => window.fixture.input().draft), '')
  const notice = page.getByRole('alert')
  await notice.filter({ hasText: '已创建任务：' }).waitFor()
  assert.equal(await page.getByTestId('capture-slot').innerHTML(), '', 'feedback must not occupy the composer slot')
  assert.equal(await notice.evaluate(element => element.parentElement === document.body), true, 'host Toast must portal outside the composer')
  assert.equal(await notice.evaluate(element => getComputedStyle(element).position), 'fixed')
  assert.equal(await notice.evaluate(element => getComputedStyle(element).top), '40px')
  // The same outcome restarts the host toast cycle rather than reusing a faded banner.
  await composer.press('Control+s')
  await notice.filter({ hasText: '输入框没有文字或附件' }).waitFor()
  const firstEmpty = await notice.elementHandle()
  await composer.press('Control+s')
  assert.equal(await firstEmpty.evaluate(element => element.isConnected), false)
  await notice.waitFor({ state: 'hidden' })
  await composer.fill('保存失败保留附件')
  await page.evaluate(() => {
    window.fixture.stageFiles([new File(['keep'], '保留.txt', { type: 'text/plain' })])
    window.fixture.failCapture(true)
  })
  await composer.press('Control+s')
  await notice.filter({ hasText: '保存失败测试' }).waitFor()
  assert.equal(await page.getByTestId('capture-slot').innerHTML(), '')
  assert.equal(await page.evaluate(() => window.fixture.input().draft), '保存失败保留附件')
  assert.equal(await page.evaluate(() => window.fixture.input().attachmentIds.length), 1)
  await page.evaluate(() => window.fixture.failCapture(false))
  await composer.press('Control+s')
  await page.waitForFunction(() => window.fixture.captures().length === 2)
  await page.waitForFunction(() => window.fixture.input().attachmentIds.length === 0)
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await page.getByRole('button', { name: /编辑: 保存失败保留附件/ }).click()
  assert.equal(await sessionPicker.inputValue(), 'session-current')
  assert.equal(await sessionPicker.locator('option:checked').innerText(), '当前中文会话')
  await page.evaluate(() => window.fixture.removeSession('session-current'))
  await page.getByRole('option', { name: '会话已不存在或暂不可用' }).waitFor({ state: 'attached' })
  assert.equal(await sessionPicker.inputValue(), 'session-current', 'deleted session must not be silently unlinked')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.fixture.tasks()[0].sessionId), 'session-current')
  assert.deepEqual(errors, [])
  console.log('Browser regression passed: formatting, save/reopen, attachment upload/download/remove, shortcut isolation, light/dark, sanitized web/Word HTML, links, nested lists, tables, undo/redo, Ctrl+S text/files/images, failure retention')
} catch (error) { console.error(error); throw error } finally { await browser.close() }
